import androidx.hilt.navigation.compose.hiltViewModel
import androidx.lifecycle.compose.collectAsStateWithLifecycle
import com.example.jobtracker.ui.navigation.AppNavigation
import com.example.jobtracker.ui.settings.SettingsViewModel
import com.example.jobtracker.ui.theme.JobTrackerTheme
import dagger.hilt.android.AndroidEntryPoint

@AndroidEntryPoint
class MainActivity : ComponentActivity() {
    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        enableEdgeToEdge()
        setContent {
            // Read the saved theme settings and pass them to the theme
            val settingsViewModel: SettingsViewModel = hiltViewModel()
            val themeMode by settingsViewModel.themeMode.collectAsStateWithLifecycle()

            JobTrackerTheme(themeMode = themeMode) {
                AppNavigation()
            }
        }
    }
}

